// SPI BUS B (IMU + ALTIMETERS)
// ============================================================
#define SCLK_B 35
#define MISO_B 37
#define MOSI_B 36

// ============================================================
// IMU (ISM330DHCX)
// ============================================================
#define IMU_CS 41
